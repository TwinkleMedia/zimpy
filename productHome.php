<script>

document.addEventListener("DOMContentLoaded", function () {

    const viewport = document.getElementById("zimpyProductViewport");
    const slides = document.querySelectorAll(".zimpy-product-slide");
    const prevButton = document.getElementById("zimpyProductPrev");
    const nextButton = document.getElementById("zimpyProductNext");
    const currentNumber = document.getElementById("zimpyProductCurrent");
    const totalNumber = document.getElementById("zimpyProductTotal");
    const progress = document.getElementById("zimpyProductProgress");

    if (!viewport || !slides.length) return;

    /* GET VISIBLE PRODUCTS */
    function getVisibleSlides() {
        if (window.innerWidth < 640) return 1;
        if (window.innerWidth < 1024) return 2;
        return 3;
    }

    /* GET CURRENT SLIDE */
    function getCurrentIndex() {
        const scrollLeft = viewport.scrollLeft;
        const slideWidth = slides[0].offsetWidth;
        const gap = parseFloat(
            getComputedStyle(document.getElementById("zimpyProductSlider")).gap
        ) || 0;
        const itemWidth = slideWidth + gap;
        return Math.round(scrollLeft / itemWidth);
    }

    /* GET MAX INDEX */
    function getMaxIndex() {
        return Math.max(0, slides.length - getVisibleSlides());
    }

    /* UPDATE UI */
    function updateUI() {
        const currentIndex = Math.min(getCurrentIndex(), getMaxIndex());
        const maxIndex = getMaxIndex();

        currentNumber.textContent = String(currentIndex + 1).padStart(2, "0");
        totalNumber.textContent = String(maxIndex + 1).padStart(2, "0");

        const percentage = maxIndex === 0
            ? 100
            : ((currentIndex + 1) / (maxIndex + 1)) * 100;

        progress.style.width = `${percentage}%`;

        prevButton.disabled = currentIndex <= 0;
        nextButton.disabled = currentIndex >= maxIndex;
    }

    /* SCROLL TO SLIDE */
    function scrollToSlide(index) {
        const maxIndex = getMaxIndex();
        index = Math.max(0, Math.min(index, maxIndex));

        slides[index].scrollIntoView({
            behavior: "smooth",
            block: "nearest",
            inline: "start"
        });
    }

    /* NEXT BUTTON */
    nextButton.addEventListener("click", function () {
        scrollToSlide(getCurrentIndex() + 1);
    });

    /* PREVIOUS BUTTON */
    prevButton.addEventListener("click", function () {
        scrollToSlide(getCurrentIndex() - 1);
    });

    /* NATIVE TOUCH / MOUSE SCROLL */
    viewport.addEventListener("scroll", function () {
        updateUI();
    }, { passive: true });

    /* RESIZE */
    window.addEventListener("resize", function () {
        updateUI();
    });

    /* INITIALIZE */
    updateUI();

});

